#!/usr/bin/env python3
"""Convert wallpaper.png into a compact RLE C header for PAPEROS.

Uses Pillow (already installed). No network access. The generated palette
exactly matches init_palette() in kernel.c.
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "wallpaper.png")
DST = os.path.join(ROOT, "wallpaper.h")

WIDTH = 1024
HEIGHT = 752          # largest supported desktop area (1024x768 minus taskbar)



def palette_bytes():
    base = [
        (0, 0, 0), (0, 0, 42), (0, 42, 0), (0, 42, 42),
        (42, 0, 0), (42, 0, 42), (42, 21, 0), (42, 42, 42),
        (21, 21, 21), (21, 21, 63), (21, 63, 21), (21, 63, 63),
        (63, 21, 21), (63, 21, 63), (63, 63, 0), (63, 63, 63),
    ]
    pal = []
    for r, g, b in base:
        pal.extend((r, g, b))
    for r in range(6):
        for g in range(6):
            for b in range(6):
                pal.extend((r * 12, g * 12, b * 12))
    for i in range(24):
        v = i * 2 + 15
        pal.extend((v, v, v))
    return bytes(pal)


def rle(data):
    out = bytearray()
    i = 0
    while i < len(data):
        count = 1
        while i + count < len(data) and data[i + count] == data[i] and count < 255:
            count += 1
        out.append(count)
        out.append(data[i])
        i += count
    return bytes(out)


def main():
    if not os.path.exists(SRC):
        raise SystemExit("missing wallpaper.png")
    src = Image.open(SRC).convert("RGB")
    img = src.resize((WIDTH, 768), Image.Resampling.LANCZOS).crop((0, 0, WIDTH, HEIGHT))

    pal_img = Image.new("P", (1, 1))
    pal_img.putpalette(palette_bytes())
    q = img.quantize(palette=pal_img, dither=Image.Dither.FLOYDSTEINBERG)
    raw = bytes(q.getdata())
    enc = rle(raw)

    with open(DST, "w") as f:
        f.write("#ifndef PAPEROS_WALLPAPER_H\n#define PAPEROS_WALLPAPER_H\n\n")
        f.write("/* Generated by make_wallpaper.py from wallpaper.png. Do not edit. */\n")
        f.write(f"#define WALL_W {WIDTH}\n#define WALL_H {HEIGHT}\n")
        f.write(f"#define WALL_RLE_LEN {len(enc)}\n\n")
        f.write("static const u8 wall_rle[WALL_RLE_LEN] = {\n")
        for i in range(0, len(enc), 16):
            chunk = ", ".join(str(b) for b in enc[i:i + 16])
            f.write("    " + chunk + ",\n")
        f.write("};\n\n#endif\n")

    print(f"wallpaper: {WIDTH}x{HEIGHT}, {len(raw)} bytes raw, {len(enc)} bytes RLE")
    print("wrote", DST)


if __name__ == "__main__":
    main()
