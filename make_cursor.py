"""Convert cursor.cur into PAPEROS cursor.h.

The CUR file is a 32x32 Windows cursor with a transparent canvas. PIL reads it
as RGBA; we crop to the visible alpha bounding box so the kernel only stores
the pixels it actually draws. The kernel palette is the 16-colour base plus a
6x6x6 colour cube and a 24-step grayscale ramp, so each pixel is reduced to
the nearest matching palette index. Output is an 8-bpp colour byte per visible
pixel plus an MSB-first transparency mask (CUR_W x CUR_H).
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "cursor.cur"
OUT = ROOT / "cursor.h"

ALPHA_CUTOFF = 96


def palette():
    pal = [
        (0, 0, 0), (0, 0, 42), (0, 42, 0), (0, 42, 42),
        (42, 0, 0), (42, 0, 42), (42, 21, 0), (42, 42, 42),
        (21, 21, 21), (21, 21, 63), (21, 63, 21), (21, 63, 63),
        (63, 21, 21), (63, 21, 63), (63, 63, 0), (63, 63, 63),
    ]
    for r in range(6):
        for g in range(6):
            for b in range(6):
                pal.append((r * 12, g * 12, b * 12))
    for i in range(24):
        v = i * 2 + 15
        pal.append((v, v, v))
    return pal


PAL = palette()


def nearest(rgb):
    src = tuple(min(63, (c * 63 + 127) // 255) for c in rgb)
    best_i, best_d = 0, 1 << 30
    for i, p in enumerate(PAL):
        d = sum((a - b) * (a - b) for a, b in zip(src, p))
        if d < best_d:
            best_i, best_d = i, d
    return best_i


def emit(name, values):
    lines = [f"static const u8 {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 16):
        lines.append("    " + ",".join(f"0x{v:02X}" for v in values[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    im = Image.open(SRC).convert("RGBA")
    bbox = im.getchannel("A").getbbox()
    if bbox:
        im = im.crop(bbox)
    cw, ch = im.size
    stride = (cw + 7) // 8

    mask = [0] * (stride * ch)
    pixels = []
    for y in range(ch):
        for x in range(cw):
            r, g, b, a = im.getpixel((x, y))
            if a < ALPHA_CUTOFF:
                pixels.append(0)
                continue
            mask[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
            pixels.append(nearest((r, g, b)))

    text = f"""/* Generated by make_cursor.py from cursor.cur. Do not edit by hand. */
#define CUR_W {cw}
#define CUR_H {ch}
#define CUR_MASK_BYTES {len(mask)}

{emit('cursor_mask', mask)}

{emit('cursor_pixels', pixels)}
"""
    OUT.write_text(text, encoding="ascii")
    print(f"wrote {OUT} ({cw}x{ch}, {len(mask)} mask bytes, {len(pixels)} colour bytes)")


if __name__ == "__main__":
    main()
