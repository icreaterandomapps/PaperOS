#!/usr/bin/env python3
"""Build PAPEROS with tools already installed on this Windows PC.

No downloads, no network. Outputs:
  os.img          bootable 1.44 MiB floppy image (Live desktop)
  paperos.iso     bootable El Torito CD image (boots the same floppy image)
  disk.img        blank 16 MiB IDE disk for the Install option (created once)
"""
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BOOT_S = os.path.join(ROOT, "boot.S")
BOOT2_S = os.path.join(ROOT, "boot2.S")
KERNEL_C = os.path.join(ROOT, "kernel.c")
LINK_LD = os.path.join(ROOT, "link.ld")

ISO_SECTOR = 2048
ISO_PVD_LBA = 16
ISO_BVD_LBA = 17
ISO_TERM_LBA = 18
ISO_CATALOG_LBA = 19
ISO_BOOT_LBA = 20
DISK_SECTORS = 32768  # 16 MiB blank install target


def run(cmd):
    print("  " + " ".join(cmd))
    subprocess.check_call(cmd, cwd=ROOT)


def put_le16(buf, off, val):
    buf[off:off + 2] = struct.pack("<H", val)


def put_be16(buf, off, val):
    buf[off:off + 2] = struct.pack(">H", val)


def put_le32(buf, off, val):
    buf[off:off + 4] = struct.pack("<I", val)


def put_be32(buf, off, val):
    buf[off:off + 4] = struct.pack(">I", val)


def pad_id(text, size):
    data = text.encode("ascii")
    return data + b" " * (size - len(data))


def dir_record(name, lba, size, flags=0):
    if isinstance(name, str):
        name = name.encode("ascii")
    else:
        name = bytes(name)
    length = 33 + len(name)
    if length & 1:
        length += 1
    rec = bytearray(length)
    rec[0] = length
    # Fixed date: 2000-01-01 00:00:00, GMT offset 0.
    rec[18:25] = bytes([100, 1, 1, 0, 0, 0, 0])
    rec[25] = flags
    rec[30] = len(name)
    rec[31:31 + len(name)] = name
    put_le32(rec, 2, lba)
    put_be32(rec, 6, lba)
    put_le32(rec, 10, size)
    put_be32(rec, 14, size)
    return bytes(rec)


def iso_date():
    return (b"2026112400000000" + bytes([0]))[:17]


def emit_c_array(name, data):
    lines = [f"static const u8 {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(str(b) for b in data[i:i + 16])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def emit_boot_images(boot, boot2):
    text = (
        "#ifndef PAPEROS_BOOT_IMAGES_H\n"
        "#define PAPEROS_BOOT_IMAGES_H\n"
        "/* Generated by build.py from the assembled boot sectors. */\n"
        + emit_c_array("boot1_image", boot) + "\n"
        + emit_c_array("boot2_image", boot2) + "\n"
        "#endif\n"
    )
    with open(os.path.join(ROOT, "boot_images.h"), "w") as f:
        f.write(text)


def build_iso(floppy, path):
    boot_sectors = (len(floppy) + ISO_SECTOR - 1) // ISO_SECTOR
    root_lba = ISO_BOOT_LBA + boot_sectors
    readme_lba = root_lba + 1
    path_lba_le = readme_lba + 1
    path_lba_be = path_lba_le + 1
    total_sectors = path_lba_be + 1

    readme = (b"PAPEROS bootable ISO\r\n"
              b"Built locally with build.py - no external ISO tools.\r\n"
              b"Boot in QEMU with: -cdrom paperos.iso -boot d\r\n")
    root_rec = dir_record(b"\x00", root_lba, 2048, 2)
    parent_rec = dir_record(b"\x01", root_lba, 2048, 2)
    file_rec = dir_record(b"README.TXT;1", readme_lba, len(readme))
    root_dir = root_rec + parent_rec + file_rec

    path_le = bytearray(10)
    path_le[0] = 1
    put_le32(path_le, 2, root_lba)
    put_le16(path_le, 6, 1)

    path_be = bytearray(10)
    path_be[0] = 1
    put_be32(path_be, 2, root_lba)
    put_be16(path_be, 6, 1)

    image = bytearray(total_sectors * ISO_SECTOR)

    # Primary Volume Descriptor.
    pvd = bytearray(ISO_SECTOR)
    pvd[0] = 1
    pvd[1:6] = b"CD001"
    pvd[6] = 1
    pvd[8:40] = pad_id("PAPEROS", 32)
    pvd[40:72] = pad_id("PAPEROS_ISO", 32)
    put_le32(pvd, 80, total_sectors)
    put_be32(pvd, 84, total_sectors)
    put_le16(pvd, 120, 1)
    put_be16(pvd, 122, 1)
    put_le16(pvd, 124, 1)
    put_be16(pvd, 126, 1)
    put_le16(pvd, 128, ISO_SECTOR)
    put_be16(pvd, 130, ISO_SECTOR)
    put_le32(pvd, 132, len(path_le))
    put_le32(pvd, 136, len(path_be))
    put_le32(pvd, 140, path_lba_le)
    put_le32(pvd, 144, 0)
    put_be32(pvd, 148, path_lba_be)
    put_be32(pvd, 152, 0)
    pvd[156:156 + len(root_rec)] = root_rec
    pvd[190:318] = pad_id("PAPEROS", 128)
    pvd[318:446] = pad_id("PAPEROS", 128)
    pvd[446:574] = pad_id("LOCAL BUILD", 128)
    pvd[574:702] = pad_id("PAPEROS BUILD.PY", 128)
    pvd[814:831] = iso_date()
    pvd[831:848] = iso_date()
    pvd[848:865] = b"0" * 17
    pvd[865:882] = iso_date()
    pvd[882] = 1
    image[ISO_PVD_LBA * ISO_SECTOR:(ISO_PVD_LBA + 1) * ISO_SECTOR] = pvd

    # El Torito Boot Record Volume Descriptor.
    bvd = bytearray(ISO_SECTOR)
    bvd[0] = 0
    bvd[1:6] = b"CD001"
    bvd[6] = 1
    # SeaBIOS compares from byte 1: "CD001\001EL TORITO SPECIFICATION".
    bvd[7:30] = b"EL TORITO SPECIFICATION"  # exact, no trailing space
    put_le32(bvd, 71, ISO_CATALOG_LBA)
    image[ISO_BVD_LBA * ISO_SECTOR:(ISO_BVD_LBA + 1) * ISO_SECTOR] = bvd

    term = bytearray(ISO_SECTOR)
    term[0] = 255
    term[1:6] = b"CD001"
    term[6] = 1
    image[ISO_TERM_LBA * ISO_SECTOR:(ISO_TERM_LBA + 1) * ISO_SECTOR] = term

    # Boot catalog: validation entry + 1.44 MiB floppy emulation entry.
    cat = bytearray(ISO_SECTOR)
    cat[0] = 1
    cat[1] = 0
    cat[2:4] = b"PO"
    cat[4:28] = pad_id("PAPEROS BOOT CATALOG", 24)
    cat[30] = 0x55
    cat[31] = 0xAA
    words = struct.unpack("<15H", bytes(cat[0:30]))
    checksum = (-sum(words)) & 0xFFFF
    put_le16(cat, 28, checksum)
    cat[32] = 0x88                     # bootable
    cat[33] = 0x02                     # SeaBIOS media 2 = 1.44 MiB floppy
    put_le16(cat, 38, 1)               # load one 2 KiB sector; INT 13h reads the rest
    put_le32(cat, 40, ISO_BOOT_LBA)
    image[ISO_CATALOG_LBA * ISO_SECTOR:(ISO_CATALOG_LBA + 1) * ISO_SECTOR] = cat

    # Boot image: the floppy image is 720 ISO sectors of 2048 bytes.
    boot_start = ISO_BOOT_LBA * ISO_SECTOR
    image[boot_start:boot_start + len(floppy)] = floppy

    root_start = root_lba * ISO_SECTOR
    image[root_start:root_start + len(root_dir)] = root_dir
    file_start = readme_lba * ISO_SECTOR
    image[file_start:file_start + len(readme)] = readme
    ple = path_lba_le * ISO_SECTOR
    pbe = path_lba_be * ISO_SECTOR
    image[ple:ple + len(path_le)] = path_le
    image[pbe:pbe + len(path_be)] = path_be

    with open(path, "wb") as f:
        f.write(image)
    return total_sectors


def main():
    boot_o = os.path.join(ROOT, "boot.o")
    boot_bin = os.path.join(ROOT, "boot.bin")
    boot2_o = os.path.join(ROOT, "boot2.o")
    boot2_elf = os.path.join(ROOT, "boot2.elf")
    boot2_bin = os.path.join(ROOT, "boot2.bin")
    kern_o = os.path.join(ROOT, "kernel.o")
    kern_elf = os.path.join(ROOT, "kernel.elf")
    kern_bin = os.path.join(ROOT, "kernel.bin")
    img = os.path.join(ROOT, "os.img")
    iso = os.path.join(ROOT, "paperos.iso")
    disk = os.path.join(ROOT, "disk.img")

    print("[1/8] Assembling stage-1 bootloader ...")
    run(["as", "--32", "-o", boot_o, BOOT_S])
    run(["objcopy", "-O", "binary", "--only-section=.text", boot_o, boot_bin])
    boot = open(boot_bin, "rb").read()
    if len(boot) != 512:
        sys.exit(f"ERROR: stage-1 bootloader is {len(boot)} bytes, expected 512")
    if boot[510:512] != b"\x55\xaa":
        sys.exit("ERROR: boot signature missing")

    print("[2/8] Assembling stage-2 bootloader ...")
    run(["as", "--32", "-o", boot2_o, BOOT2_S])
    run(["ld", "-m", "i386pe", "-Ttext", "0x7E00", "-o", boot2_elf, boot2_o])
    run(["objcopy", "-O", "binary", "--only-section=.text", boot2_elf, boot2_bin])
    boot2 = bytearray(open(boot2_bin, "rb").read())
    boot2_raw_size = len(boot2)
    if boot2_raw_size > 2048:
        sys.exit(f"ERROR: stage-2 bootloader is {boot2_raw_size} bytes, max 2048")
    boot2 += b"\x00" * (2048 - boot2_raw_size)
    emit_boot_images(boot, bytes(boot2))   # placeholder for the first compile

    print("[3/8] Compiling freestanding 32-bit kernel ...")
    cflags = [
        "-m32", "-O0", "-ffreestanding", "-fno-pic", "-fno-stack-protector",
        "-fno-builtin", "-fno-asynchronous-unwind-tables", "-fno-tree-vectorize",
        "-nostdlib",
        "-Wall", "-Wno-unused-function",
    ]
    run(["gcc"] + cflags + ["-c", KERNEL_C, "-o", kern_o])

    print("[4/8] Linking flat kernel image ...")
    run(["ld", "-m", "i386pe", "-T", LINK_LD, "-o", kern_elf, kern_o])
    run(["objcopy", "-O", "binary", "--only-section=.text", kern_elf, kern_bin])
    kernel = open(kern_bin, "rb").read()
    max_sectors = 768
    sectors = (len(kernel) + 511) // 512
    if sectors > max_sectors:
        sys.exit(f"ERROR: kernel is {len(kernel)} bytes ({sectors} sectors), "
                 f"stage 2 only loads {max_sectors} sectors")

    # Patch the kernel sector count into stage 2 before it is packed.
    marker = boot2.find(b"KSEC")
    if marker < 0:
        sys.exit("ERROR: KSEC marker missing from stage 2")
    boot2[marker + 4:marker + 6] = struct.pack("<H", sectors)
    open(boot2_bin, "wb").write(boot2)

    # Regenerate the embedded pristine boot images with the patched sector
    # count, then rebuild the kernel. The array size is fixed, so the kernel
    # size and KSEC value cannot change on this second pass.
    emit_boot_images(boot, bytes(boot2))
    run(["gcc"] + cflags + ["-c", KERNEL_C, "-o", kern_o])
    run(["ld", "-m", "i386pe", "-T", LINK_LD, "-o", kern_elf, kern_o])
    run(["objcopy", "-O", "binary", "--only-section=.text", kern_elf, kern_bin])
    kernel = open(kern_bin, "rb").read()
    if (len(kernel) + 511) // 512 != sectors:
        sys.exit("ERROR: kernel size changed while embedding boot images")

    # Memory map checks.
    back_base = 0x100000
    desktop_base = 0x1000000
    canvas_base = 0x1A00000
    pristine_base = 0x1C00000
    max_frame = 3840 * 2160
    max_canvas = 1600 * 1200
    if 0x10000 + len(kernel) >= 0x80000:
        sys.exit("ERROR: kernel overlaps the stack at 0x80000")
    if 0x10000 + len(kernel) >= back_base:
        sys.exit("ERROR: kernel overlaps the back buffer at 0x100000")
    if desktop_base < back_base + max_frame:
        sys.exit("ERROR: DESKTOP overlaps BACK at 3840x2160")
    if canvas_base < desktop_base + max_frame:
        sys.exit("ERROR: Paint canvas overlaps DESKTOP at 3840x2160")
    if canvas_base + max_canvas > pristine_base:
        sys.exit("ERROR: Paint canvas overlaps the pristine kernel copy")
    if pristine_base + max_sectors * 512 > 64 * 1024 * 1024:
        sys.exit("ERROR: pristine kernel copy exceeds the 64 MiB guest RAM")

    print("[5/8] Building bootable disk image ...")
    image = bytearray(boot)
    image += boot2                     # sectors 1-4
    image += kernel                    # starts at LBA 5
    image += b"\x00" * (512 - len(kernel) % 512)
    image += b"\x00" * (2880 * 512 - len(image))
    open(img, "wb").write(image)

    print("[6/8] Building bootable ISO ...")
    iso_sectors = build_iso(bytes(image), iso)

    print("[7/8] Preparing blank IDE install target ...")
    # Always start from a clean target. Reusing an old image can leave a stale
    # PAPEROSFS superblock at the old LBA 400 and mask installer bugs.
    with open(disk, "wb") as f:
        f.truncate(DISK_SECTORS * 512)

    print("[8/8] Done.")
    print(f"  stage 1    : 512 bytes")
    print(f"  stage 2    : {len(boot2)} bytes ({boot2_raw_size} raw)")
    print(f"  kernel     : {len(kernel)} bytes ({sectors} sectors)")
    print(f"  os.img     : {len(image)} bytes ({len(image)//1024} KiB)")
    print(f"  paperos.iso: {os.path.getsize(iso)} bytes ({iso_sectors} ISO sectors)")
    print(f"  disk.img   : {os.path.getsize(disk)} bytes (install target)")
    print("  Run: run.bat | run_iso.bat | run_install.bat")


if __name__ == "__main__":
    main()
